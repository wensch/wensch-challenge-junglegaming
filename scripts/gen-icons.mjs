// Generates src/components/icons/figma.tsx from the SVGs exported from Figma (design/icons/*.svg).
// Monochrome icons take their color from the surrounding text (`currentColor`); brand logos that are
// multi-color keep theirs. Masks and clip paths get per-instance ids (useId) so an icon can appear many times.
// Run: node scripts/gen-icons.mjs
import { readFileSync, readdirSync, writeFileSync } from 'node:fs'
import { basename, join } from 'node:path'

const SRC = 'design/icons'
const OUT = 'src/components/icons/figma.tsx'

// Figma layer name -> component name.
const NAMES = {
  Activity: 'ActivityIcon',
  'Arrow - Left 2': 'ArrowLeftIcon',
  Cart: 'CartIcon',
  'Danger Triangle': 'DangerTriangleIcon',
  Download: 'DownloadIcon',
  'Ellipse 2 (Stroke)': 'EllipseStrokeIcon',
  Filter: 'FilterIcon',
  Group: 'ScanIcon',
  Hide: 'HideIcon',
  Home: 'HomeIcon',
  Location: 'LocationIcon',
  Logout: 'LogoutIcon',
  'Search Icon': 'SearchIcon',
  Shop: 'ShopIcon',
  Star: 'StarIcon',
  User: 'UserIcon',
  Vector: 'HeartIcon',
  'facebook-login': 'FacebookLoginIcon',
  facebook: 'FacebookIcon',
  'google 1': 'GoogleIcon',
  instagram: 'InstagramIcon',
  linkedin: 'LinkedinIcon',
  shopping1: 'ShoppingBagIcon',
  twitter: 'TwitterIcon',
  youtube: 'YoutubeIcon',
}
// Keep the original colors (brand logos).
const KEEP_COLORS = new Set(['facebook-login', 'google 1'])

const camel = (s) => s.replace(/-([a-z])/g, (_, c) => c.toUpperCase())

function convert(file, key, name) {
  let svg = readFileSync(join(SRC, file), 'utf8').replace(/\r/g, '').trim()
  const open = svg.match(/<svg\b([^>]*)>/)
  const attrs = open[1]
  const viewBox = attrs.match(/viewBox="([^"]+)"/)[1]
  const width = attrs.match(/width="([^"]+)"/)[1]
  const height = attrs.match(/height="([^"]+)"/)[1]
  let body = svg.slice(open.index + open[0].length, svg.lastIndexOf('</svg>')).trim()

  if (!KEEP_COLORS.has(key)) body = body.replace(/(stroke|fill)="#[0-9A-Fa-f]{3,8}"/g, '$1="currentColor"')

  // ids used by masks / clip paths -> per-instance ids
  const ids = [...body.matchAll(/\sid="([^"]+)"/g)].map((m) => m[1])
  for (const id of ids) {
    body = body.replaceAll(`id="${id}"`, `id={\`\${uid}-${id}\`}`)
    body = body.replaceAll(`url(#${id})`, `url(#\${uid}-${id})`)
  }
  // attributes that carry a url(#...) must become template literals
  body = body.replace(/(mask|clip-path)="(url\(#\$\{uid\}-[^)]+\))"/g, (_, a, v) => `${camel(a)}={\`${v}\`}`)
  body = body.replace(/style="mask-type:(\w+)"/g, "style={{ maskType: '$1' }}")
  body = body.replace(/\s([a-z]+(?:-[a-z]+)+)="/g, (m, a) => ` ${camel(a)}="`)
  body = body.replace(/\sxmlns(:\w+)?="[^"]*"/g, '')

  const useId = ids.length > 0
  const indent = (s, n) => s.split('\n').map((l) => ' '.repeat(n) + l.trim()).join('\n')
  return `export function ${name}(props: IconProps) {
${useId ? '  const uid = useId()\n' : ''}  return (
    <svg width={${width}} height={${height}} viewBox="${viewBox}" fill="none" aria-hidden="true" focusable="false" {...props}>
${indent(body, 6)}
    </svg>
  )
}
`
}

const files = readdirSync(SRC).filter((f) => f.endsWith('.svg')).sort()
const parts = []
const unknown = []
for (const f of files) {
  const key = basename(f, '.svg')
  const name = NAMES[key]
  if (!name) {
    unknown.push(f)
    continue
  }
  parts.push(convert(f, key, name))
}
if (unknown.length) console.warn('No component name for:', unknown.join(', '))

const header = `/* Generated by scripts/gen-icons.mjs from design/icons/*.svg (Figma exports). Do not edit by hand. */
import { useId, type SVGProps } from 'react'

export type IconProps = SVGProps<SVGSVGElement>

`
writeFileSync(OUT, header + parts.join('\n'))
console.log(`wrote ${OUT}: ${parts.length} icons`)
